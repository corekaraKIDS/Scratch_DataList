//ページ読み込み時の処理
document.addEventListener("DOMContentLoaded", ()=>{
  // 教材用テーブル描画
  renderSections(materials_taiken, "table-taiken", false);
  renderSections(materials_syokyuu, "table-syokyuu", false);
  renderSections(materials_tyuukyuu, "table-tyuukyuu", false);
  renderSections(materials_joukyuu, "table-joukyuu", false);

  //生徒作品用テーブル描画
  renderSections(materials_students, "table-students", true);

  switchTab('text');
});

//タブ切り替え関数
function switchTab(tabName){
  // コンテンツエリアを取得
  const textContent=document.getElementById('content-text');
  const studentsContent=document.getElementById('content-students');
  //ボタンを取得
  const textBtn=document.getElementById('tab-text');
  const studentsBtn=document.getElementById('tab-students');

  const jumpToContainer=document.getElementById('jump-to-container');

  if(tabName==='text'){
    //教材を表示、生徒作品を非表示
    textContent.classList.remove('hidden');
    studentsContent.classList.add('hidden');
    
    //教材タブ中はJump to...を表示
    if(jumpToContainer) jumpToContainer.classList.remove('hidden');

    //ボタンのスタイルを変更
    setActiveTabButtonStyle(textBtn);
    setInactiveTabButtonStyle(studentsBtn);
  }else if(tabName==='students'){
    //生徒作品を表示、教材を非表示
    studentsContent.classList.remove('hidden');
    textContent.classList.add('hidden');

    //生徒作品タブ中はJump to...非表示
    if(jumpToContainer) jumpToContainer.classList.add('hidden');

    //ボタンのスタイルを変更
    setActiveTabButtonStyle(studentsBtn);
    setInactiveTabButtonStyle(textBtn);
  }
}

//選択中タブ
function setActiveTabButtonStyle(btn){
  btn.className="tab-btn px-5 py-2.5 rounded-t-lg font-bold border border-b-0 border-[#ddd] bg-white text-[#333] relative z-20 transition-all";
}

//未選択タブ
function setInactiveTabButtonStyle(btn){
  btn.className="tab-btn px-5 py-2.5 rounded-t-lg font-bold border border-b-0 border-[#ddd] bg-[#e6f0fa] text-[#007bff] hover:bg-[#d8e8f8] relative z-0 transition-all";
}

function renderSections(sections, containerId, isStudent=false){
  const container=document.getElementById(containerId);
  if(!container) return;

  container.replaceChildren();
  container.classList.add('space-y-8');

  const sectionColors={
    'table-syokyuu': 'border-green-200 bg-green-100',
    'table-tyuukyuu': 'border-yellow-200 bg-yellow-100',
    'table-joukyuu': 'border-red-200 bg-red-100'
  };
  const sectionColor=sectionColors[containerId] || 'border-slate-200 bg-slate-100';

  sections.forEach((section, index)=>{
    const sectionElement=document.createElement('section');
    sectionElement.className=`border ${sectionColor} rounded-lg p-4`;
    const heading=document.createElement('h3');
    heading.className='text-xl font-bold mb-3';
    heading.textContent=section.title;

    const cardsContainer=document.createElement('div');
    cardsContainer.id=`${containerId}-section-${index}`;

    sectionElement.append(heading, cardsContainer);
    container.append(sectionElement);
    renderCards(section.materials, cardsContainer.id, isStudent);
  });
}

function renderCards(dataList, containerId, isStudent=false){
  const container=document.getElementById(containerId);
  if(!container) return;

  const cardHtml=dataList.map(item=>{
    if(isStudent){
      return `
        <div class="flex items-start w-full min-w-0 h-full bg-white border-2 border-[#bbb] rounded-lg overflow-hidden shadow-sm">
            <div class="w-1/3 max-w-[160px] shrink-0 border-r border-[#ddd]">
                <a href="${encodeURI(item.link)}" target="_blank" rel="noopener noreferrer"
                   class="block w-full aspect-[4/3] bg-slate-100 border-b border-[#ddd] overflow-hidden hover:opacity-80 transition-opacity">
                    <img src="${item.image || 'images/placeholder.png'}" alt="${item.name}" class="w-full h-full object-cover">
                </a>
                <div class="p-2 text-xs [overflow-wrap:anywhere]">
                    <p class="mb-1 text-[11px] text-gray-600">作品名</p>
                    <p>${item.name}</p>
                </div>
            </div>
            <dl class="flex-1 min-w-0 p-3 space-y-3 text-xs leading-relaxed [overflow-wrap:anywhere]">
                <div>
                    <dt class="mb-1 font-bold text-gray-600">校舎・教室</dt>
                    <dd>${item.school || ''}</dd>
                </div>
                <div>
                    <dt class="mb-1 font-bold text-gray-600">生徒名</dt>
                    <dd>${item.student_name || ''}</dd>
                </div>
                <div>
                    <dt class="mb-1 font-bold text-gray-600">作品メモ</dt>
                    <dd class="whitespace-pre-wrap">${item.memo || ''}</dd>
                </div>
            </dl>
        </div>
      `;
    }

    return `
        <div class="flex flex-col w-full max-w-[160px] h-full bg-white border-2 border-[#bbb] rounded-lg overflow-hidden shadow-sm">
            <a href="${encodeURI(item.link)}" target="_blank" rel="noopener noreferrer"
            class="block w-full aspect-[4/3] bg-slate-100 border-b border-[#ddd] overflow-hidden hover:opacity-80 transition-opacity">
                <img src="${item.image || 'images/placeholder.png'}" alt="${item.name}" class="w-full h-full object-cover">
            </a>

            <table class="w-full flex-1 h-full border-collapse text-left">
                <thead>
                    <tr class="bg-[#f8f8f8] text-[11px] font-bold">
                        <th class="border border-[#ddd] px-2 py-0.5 text-left w-14">ID</th>
                        <th class="border border-[#ddd] px-2 py-0.5 text-left">${isStudent?'作品名':'教材名'}</th>
                    </tr>
                </thead>
                <tbody>
                    <tr>
                        <td class="border border-[#ddd] px-2 py-1 text-left text-xs whitespace-nowrap font-mono">${item.id}</td>
                        <td class="border border-[#ddd] px-2 py-1 text-left text-xs leading-snug">${item.name}</td>
                    </tr>
                </tbody>
            </table>
        </div>
    `;
  }).join("");

  const gridClass=isStudent
    ? 'grid grid-cols-1 lg:grid-cols-2 gap-4'
    : 'grid max-w-[1020px] grid-cols-1 sm:grid-cols-2 md:grid-cols-3 lg:grid-cols-4 xl:grid-cols-6 gap-3';

  container.innerHTML=`
    <div class="${gridClass}">
        ${cardHtml}
    </div>
  `;
}
